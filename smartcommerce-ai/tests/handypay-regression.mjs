import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHmac} from 'node:crypto';
import ts from 'typescript';
const source=await readFile(new URL('../src/server/payments/handypay.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {createHandyPay,verifyHandyPayEvent}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const config={apiKey:'hp_test_fixture',mode:'test',publicOrigin:'https://shop.example',checkoutOrigins:['https://checkout.stripe.com']};
const order={id:'order_fixture',amountMinor:11500,currency:'JMD'};
let calls=[];
const gateway=createHandyPay(config,async(url,options)=>{calls.push({url,options});return new Response(JSON.stringify({success:true,data:{id:'cs_test_fixture',url:'https://checkout.stripe.com/c/pay/fixture',status:'open',payment_status:'unpaid',created:1}}));});
assert.deepEqual(await gateway.create(order),{id:'cs_test_fixture',url:'https://checkout.stripe.com/c/pay/fixture'});
const request=JSON.parse(calls[0].options.body);
assert.equal(request.line_items[0].amount,11500);assert.equal(request.line_items[0].currency,'jmd');
assert.equal(request.metadata.order_id,order.id);assert.equal(request.pass_fees_to_customer,false);
assert.equal(calls[0].url,'https://api.handypay.me/api/v1/payment-sessions');
assert.equal(calls[0].options.redirect,'error');
await assert.rejects(()=>gateway.create({...order,amountMinor:11.5}),/PAYMENT_INVALID_ORDER/);
assert.throws(()=>createHandyPay({...config,mode:'live'}),/PAYMENT_CONFIGURATION/);
const timeout=createHandyPay(config,async()=>{throw new Error('secret provider error');});
await assert.rejects(()=>timeout.create(order),e=>e.message==='PAYMENT_RECONCILIATION_REQUIRED');
const bad=createHandyPay(config,async()=>new Response(JSON.stringify({success:true,data:{id:'cs_fixture',url:'https://evil.example/pay'}})));
await assert.rejects(()=>bad.create(order),/PAYMENT_RECONCILIATION_REQUIRED/);
const paid={id:'cs_test_fixture',status:'complete',payment_status:'paid',amount_total:11500,currency:'jmd',metadata:{order_id:order.id}};
const lookup=data=>createHandyPay(config,async()=>new Response(JSON.stringify({success:true,data})));
assert.equal((await lookup(paid).verify('cs_test_fixture',order)).status,'paid');
for(const changed of [{amount_total:100},{metadata:{}},{id:'cs_other'},{currency:'usd'}])assert.equal((await lookup({...paid,...changed}).verify('cs_test_fixture',order)).status,'needs_review');
assert.equal((await lookup({...paid,payment_status:'unpaid'}).verify('cs_test_fixture',order)).status,'pending');
const raw=Buffer.from(JSON.stringify({id:'evt_fixture',type:'checkout.session.completed',data:{id:'cs_test_fixture'}}));
const signature='sha256='+createHmac('sha256','test-secret').update(raw).digest('hex');
assert.equal(verifyHandyPayEvent(raw,signature,'test-secret').id,'evt_fixture');
for(const [body,sig,secret] of [[Buffer.concat([raw,Buffer.from(' ')]),signature,'test-secret'],[raw,'sha256=abc','test-secret'],[raw,signature,'']])assert.throws(()=>verifyHandyPayEvent(body,sig,secret),/PAYMENT_INVALID_SIGNATURE/);
console.log('HandyPay hosted sessions, exact amounts, mode isolation, ambiguous failures, signed bytes and settlement matching passed.');
