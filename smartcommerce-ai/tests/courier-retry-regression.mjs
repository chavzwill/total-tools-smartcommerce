import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile(new URL('../src/lib/courierRetry.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {createCourierMutation}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const attempts=[];let fail=true;
const mutation=createCourierMutation(async command=>{attempts.push(command);if(fail)throw new Error('network');return {id:command.id,version:2};});
const input={action:'save_application',id:'one',input:{businessName:'Original'}};
await assert.rejects(()=>mutation.run(input));
input.input.businessName='Changed';
await assert.rejects(()=>mutation.run(input),/pending/);
fail=false;await mutation.retry();
assert.deepEqual(attempts[0],attempts[1]);
assert.equal(attempts[1].input.businessName,'Original');
await mutation.run(input);
assert.notEqual(attempts[1].idempotencyKey,attempts[2].idempotencyKey);
let finish;const slow=createCourierMutation(()=>new Promise(resolve=>{finish=resolve;}));
const pending=slow.run({action:'submit_application'});
await assert.rejects(()=>slow.retry(),/progress/);
finish({version:1});await pending;
console.log('Courier mutations preserve payload and key after uncertain failures and block concurrent writes.');
