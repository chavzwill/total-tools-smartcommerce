import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const code=ts.transpileModule(await readFile(new URL('../src/server/couriers/privateData.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {seal,unseal,validateDocument,newPickupCredential,credentialHash}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
assert.throws(()=>seal(Buffer.from('private'),''));
const key=Buffer.alloc(32,7).toString('base64');const boxed=seal(Buffer.from('private'),key);
assert.equal(unseal(boxed,key).toString(),'private');
const tampered={...boxed,body:Buffer.from('changed').toString('base64')};assert.throws(()=>unseal(tampered,key));
assert.throws(()=>unseal(boxed,Buffer.alloc(32,8).toString('base64')));
assert.throws(()=>validateDocument(Buffer.from('<script>bad</script>'),'image/png'));
assert.throws(()=>validateDocument(Buffer.alloc(5*1024*1024+1),'image/jpeg'));
const bounded=Buffer.alloc(2*1024*1024);bounded.set([255,216,255]);assert.equal(validateDocument(bounded,'image/jpeg'),'image/jpeg');assert.throws(()=>validateDocument(Buffer.concat([bounded,Buffer.from([0])]),'image/jpeg'));
assert.equal(validateDocument(Buffer.from([255,216,255,224,0,1]),'image/jpeg'),'image/jpeg');
assert.equal(validateDocument(Buffer.from('%PDF-1.7\n'),'application/pdf'),'application/pdf');
const a=newPickupCredential(),b=newPickupCredential();assert.notEqual(a,b);assert.equal(credentialHash(a).length,64);assert.ok(!credentialHash(a).includes(a));
console.log('Courier private document encryption, tamper rejection, upload bounds and opaque pickup credentials passed.');
const QRCode=(await import('qrcode')).default;
const address='https://example.test/#/operations/courier-security?pickup='+a;
const qr=QRCode.create(address,{errorCorrectionLevel:'M'});assert.ok(qr.modules.size>20);assert.match(await QRCode.toDataURL(address),/^data:image\/png;base64,/);
console.log('Pickup pass renders as a QR image carrying a staff lookup reference.');
